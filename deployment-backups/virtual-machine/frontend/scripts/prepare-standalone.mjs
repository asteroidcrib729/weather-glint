import { cpSync, existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const output = join(process.cwd(), ".next", "standalone");
if (!existsSync(join(output, "server.js"))) {
  throw new Error("Next.js standalone server was not generated by the build.");
}

mkdirSync(join(output, ".next"), { recursive: true });
cpSync(join(process.cwd(), ".next", "static"), join(output, ".next", "static"), { recursive: true });
if (existsSync(join(process.cwd(), "public"))) {
  cpSync(join(process.cwd(), "public"), join(output, "public"), { recursive: true });
}
